ALTER TABLE public."COMPONENT" 
    DROP CONSTRAINT "COMPONENT_LICENSE_FK",
    DROP COLUMN "LICENSE_ID",
    DROP COLUMN "LICENSE",
    DROP COLUMN "LICENSE_EXPRESSION",
    DROP COLUMN "LICENSE_URL";

CREATE INDEX "COMPONENTLICENSES_COMPONENT_ORDINALITY_IDX"
    ON public."COMPONENTLICENSES" ("COMPONENTID", "ORDINALITY");
